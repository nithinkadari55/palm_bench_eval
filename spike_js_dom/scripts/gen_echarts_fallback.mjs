// Pre-generates the SVG used by case 03 when the phase 5 ECharts bundle is not reachable.
// It runs phase5_js/js/dist/shims.js + echarts.js in a node:vm context with the same option
// as the page and writes cases/assets/echarts_fallback.js.
// usage: node gen_echarts_fallback.mjs <phase5_js/js/dist> <out.js>
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const here = dirname(fileURLToPath(import.meta.url));
const [dist, out] = process.argv.slice(2);
const ctx = vm.createContext({});
vm.runInContext(readFileSync(join(dist, 'shims.js'), 'utf8'), ctx, { filename: 'shims.js' });
vm.runInContext('var reg = __p5.register; __p5.register = function (l) { globalThis.__echartsLib = l; reg(l); };', ctx);
vm.runInContext(readFileSync(join(dist, 'echarts.js'), 'utf8'), ctx, { filename: 'echarts.js' });
vm.runInContext(readFileSync(join(here, '..', 'cases', 'assets', 'echarts_option.js'), 'utf8'), ctx);
const svg = vm.runInContext('__echartsLib.run({ option: __CHART_OPTION, width: 600, height: 360 })', ctx);
const bundles = JSON.parse(readFileSync(join(dist, 'bundles.json'), 'utf8'));
writeFileSync(out, '// Generated by scripts/gen_echarts_fallback.mjs from phase5_js/js/dist/echarts.js (sha256 ' +
  bundles.bundles.echarts.sha256 + ').\nglobalThis.__ECHARTS_FALLBACK_SVG = ' + JSON.stringify(svg) + ';\n');
console.log('svg bytes', svg.length);
